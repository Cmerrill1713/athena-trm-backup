"""
STOP Optimizer - Self-Taught Optimization for AGI Core

Implements the Self-Taught Optimizer (STOP) approach from:
https://arxiv.org/abs/2310.02304

Key Concepts:
- Scaffolding programs that improve themselves
- Multiple optimization strategies (beam search, genetic algorithms, simulated annealing)
- LLM-generated improvement candidates
- Utility function-driven selection
- Sandboxed execution for safety
"""

