def get_provider(provider_id: str) -> ProviderInfo:
    """Get provider info by ID"""
    if provider_id not in PROVIDERS:
        raise ValueError(f"Unknown provider: {provider_id}")
    return PROVIDERS[provider_id]


def get_providers_by_capability(capability: str) -> List[ProviderInfo]:
    """Get all providers that support a given capability"""
    return [
        info for info in PROVIDERS.values()
        if capability in info.capabilities and info.enabled
    ]


def list_all_providers() -> Dict[str, ProviderInfo]:
    """Get all registered providers"""
    return PROVIDERS.copy()


def list_experimental_providers() -> Dict[str, ProviderInfo]:
    """Get all experimental/research providers"""
    return {
        pid: info for pid, info in PROVIDERS.items()
        if info.experimental and info.enabled
    }
