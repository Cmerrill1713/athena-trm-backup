"""
Provider Registry for Research Implementations
==============================================
Central registry for all capability providers including new research implementations
"""

from typing import Dict, List
from dataclasses import dataclass


@dataclass
class ProviderInfo:
    """Information about a registered provider"""
    name: str
    module_path: str
    capabilities: List[str]
    description: str
    enabled: bool = True
    experimental: bool = False


